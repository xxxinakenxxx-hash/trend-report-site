// =============================================================================
// archiveData.ts — 週次トレンドレポート アーカイブデータ管理ファイル
// =============================================================================
//
// 【このファイルの役割】
//   過去の週次トレンドレポートを号ごとに管理するデータファイルです。
//   毎週の発行後、このファイルに新号データを追記することで
//   「バックナンバー」ページに自動的に反映されます。
//
// =============================================================================
// 【毎週の新号追加手順】（所要時間：約15〜20分）
// =============================================================================
//
// ■ STEP 1 — 前号を「アーカイブ化」する
//   archiveIssues 配列の先頭にある最新号（isLatest: true）を探し、
//   isLatest を false に変更します。
//
//   変更前:  isLatest: true,
//   変更後:  isLatest: false,
//
// ■ STEP 2 — 新号データを配列の先頭に追加する
//   以下の「新号追加テンプレート」をコピーして、
//   archiveIssues 配列の最初の要素として貼り付けます。
//   ※ 必ず配列の「先頭」に追加してください（末尾に追加すると表示順が逆になります）
//
// ■ STEP 3 — 各フィールドを今週のデータに書き換える
//   下記「フィールド記入ガイド」を参照しながら、
//   テンプレートの各フィールドを今週の実際のデータに更新します。
//
// ■ STEP 4 — issueNumber を更新する
//   前号が「Vol.04」なら新号は「Vol.05」と、1ずつ増やします。
//
// ■ STEP 5 — 動作確認
//   ブラウザで「バックナンバー」ページを開き、
//   新号が一覧の先頭に表示されていることを確認します。
//
// =============================================================================
// 【新号追加テンプレート】（STEP 2 でコピーして使用）
// =============================================================================
//
// ─── ここからコピー ───────────────────────────────────────────────────────────
//
//   {
//     id: '2026-05-w1',                    // ← 「年-月-w週番号」の形式で記入
//     issueNumber: 'Vol.05',               // ← 前号 +1 の番号
//     weekLabel: '2026年5月第1週',          // ← 「YYYY年M月第N週」の形式
//     publishedAt: '2026-05-01',           // ← 発行日（YYYY-MM-DD）
//     isLatest: true,                      // ← 新号は必ず true
//     keywordTags: [                       // ← 今週のキーワードを3〜6個
//       'キーワード1',
//       'キーワード2',
//       'キーワード3',
//     ],
//     editorNote: '今週の一言コメントをここに記入。',  // ← 編集後記（1〜2文）
//     topTrends: [
//       {
//         rank: 1,
//         title: 'トレンド名（フルタイトル）',
//         category: 'スイーツ・洋菓子',      // ← 下記「カテゴリ一覧」から選択
//         categoryColor: '#10B981',         // ← カテゴリに対応する色コード
//         totalScore: 24,                   // ← 5項目×5点満点の合計（最大25）
//         icon: '🍵',                       // ← トレンドを象徴する絵文字1つ
//         summary: 'トレンドの概要を1〜2文で記入。営業担当が一読で把握できる内容に。',
//       },
//       // rank: 2〜5 も同様に追加
//     ],
//   },
//
// ─── ここまでコピー ───────────────────────────────────────────────────────────
//
// =============================================================================
// 【フィールド記入ガイド】
// =============================================================================
//
// ▼ id（スラッグ）
//   形式: 「YYYY-MM-wN」（N = 週番号）
//   例:   2026-05-w1（2026年5月第1週）、2026-05-w2（2026年5月第2週）
//   ※ 同じ id が重複しないよう注意してください
//
// ▼ keywordTags（キーワードタグ）
//   今週のトレンドを象徴するキーワードを3〜6個記入します。
//   アーカイブ一覧ページでタグとして表示されます。
//   例: ['抹茶テクスチャー', '新食感', '冷凍ベーカリー', 'クァベギ']
//
// ▼ editorNote（編集後記）
//   今週のレポート全体を振り返る一言コメントです。
//   「今週のポイントは〇〇でした」「〇〇の提案好機です」などの形式が読みやすいです。
//
// ▼ category（カテゴリ）と categoryColor（カテゴリ色）
//   以下の組み合わせから選択してください。他のカテゴリを追加する場合は
//   PrintFilterDialog.tsx の CATEGORY_ICONS と CATEGORY_DESC も合わせて更新してください。
//
//   カテゴリ名                    | 色コード
//   ─────────────────────────────────────────
//   'スイーツ・洋菓子'            | '#10B981'  （エメラルドグリーン）
//   'パン・ベーカリー'            | '#F5A623'  （ゴールドアンバー）
//   '冷凍食品・冷凍スイーツ'      | '#60A5FA'  （ライトブルー）
//   'カフェメニュー'              | '#A78BFA'  （ラベンダー）
//   '健康志向・高付加価値食品'    | '#34D399'  （ライトグリーン）
//
// ▼ totalScore（総合スコア）
//   5つの評価軸（話題性・検索需要・メディア露出・業務用接続性・継続可能性）を
//   各5点満点で採点した合計点を記入します（最大25点）。
//   アーカイブ詳細ページでスコアバッジとして表示されます。
//
// ▼ icon（絵文字アイコン）
//   トレンドを象徴する絵文字を1つ選んでください。
//   アーカイブ一覧・詳細ページのトレンド行頭に表示されます。
//
// =============================================================================
// 【よくある間違いと対処法】
// =============================================================================
//
//  ❌ 前号の isLatest を false に変え忘れた
//     → 「最新号」バッジが2つ表示されます。
//       archiveIssues 配列を検索して isLatest: true が1件だけになるよう修正してください。
//
//  ❌ 新号を配列の末尾に追加した
//     → バックナンバー一覧で最新号が一番下に表示されます。
//       配列の先頭（最初の { の直前）に移動してください。
//
//  ❌ id が重複している
//     → 詳細ページのURLが衝突し、古い号が表示されることがあります。
//       id は必ず一意（ユニーク）にしてください。
//
//  ❌ topTrends の rank が飛んでいる・重複している
//     → 表示順が意図しない順番になることがあります。
//       rank は 1〜5 を連番で記入してください。
//
// =============================================================================
// 【データ更新後の確認チェックリスト】
// =============================================================================
//
//  □ バックナンバー一覧（/archive）に新号が先頭に表示されている
//  □ 新号の詳細ページ（/archive/[id]）が正しく表示されている
//  □ 「最新号」バッジが新号にのみ表示されている
//  □ 前号の詳細ページに「最新号を確認する」CTAが表示されている
//  □ 前後号ナビゲーション（← 前の号 / 次の号 →）が正しく機能している
//
// =============================================================================

export interface ArchiveTrendSummary {
  rank: number;
  title: string;
  category: string;
  categoryColor: string;
  totalScore: number;
  icon: string;
  summary: string;
}

export interface ArchiveIssue {
  id: string;           // "2026-04-w4" のようなスラッグ
  issueNumber: string;  // "Vol.01" など
  weekLabel: string;    // "2026年4月第4週"
  publishedAt: string;  // "2026-04-24"
  isLatest: boolean;
  keywordTags: string[];
  topTrends: ArchiveTrendSummary[];
  editorNote: string;   // 編集後記・ひとこと
}

