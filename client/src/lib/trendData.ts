// =============================================================================
// trendData.ts — 最新号ページ データ管理ファイル
// =============================================================================
//
// 【このファイルの役割】
//   サイトのトップページ（最新号）に表示されるトレンドデータを管理します。
//   毎週このファイルを更新し、archiveData.ts に前号データを移すことで
//   2ファイルの編集だけで週次更新が完結します。
//
// =============================================================================
// 【週次更新の全体フロー（2ファイル更新で完結）】
// =============================================================================
//
//   ┌─────────────────────────────────────────────────────────────────┐
//   │  毎週の更新作業                                                  │
//   │                                                                  │
//   │  ① trendData.ts（このファイル）                                 │
//   │     └ 最新号のトレンドデータ・メール文案を今週の内容に書き換え  │
//   │                                                                  │
//   │  ② archiveData.ts                                               │
//   │     └ 前号を isLatest: false にして、新号を配列先頭に追加       │
//   │                                                                  │
//   │  ※ archiveData.ts の詳細手順は同ファイル先頭のコメントを参照   │
//   └─────────────────────────────────────────────────────────────────┘
//
// =============================================================================
// 【STEP 1 — ファイル先頭の号数コメントを更新する】
// =============================================================================
//
//   このファイル末尾にあるコメント行（「// TREND DATA — 〇〇」）を今週の号数に書き換えます。
//   例: // TREND DATA — 2026年5月第1週
//
//   ※ 画面表示には影響しませんが、担当者がどの号のデータかを一目で把握するためのものです。
//
// =============================================================================
// 【STEP 2 — trends 配列のトレンドデータを書き換える】
// =============================================================================
//
//   trends 配列（export const trends: TrendItem[] = [...] ）の中身を
//   今週の調査結果に基づいて全件書き換えます。
//   トレンドは5件（id: 1〜5）固定です。
//
//   ▼ 各フィールドの記入ガイド
//
//   id            : 1〜5 の連番。変更不要。
//   title         : トレンドのフルタイトル（20〜40文字程度）
//   shortTitle    : 評価マトリクス表に表示する短縮タイトル（10〜15文字程度）
//   category      : 下記「カテゴリ一覧」から選択
//   categoryColor : カテゴリに対応する色コード（下記「カテゴリ一覧」参照）
//   totalScore    : scores の5項目の合計点（最大25点）
//   scores        : 5つの評価軸をそれぞれ1〜5点で記入
//   summary       : トレンドの概要（2〜3文。カードに常時表示される）
//   background    : 話題化している背景・理由（3〜5文。詳細展開時に表示）
//   salesAngle    : 営業で使える切り口（2〜3文。具体的な提案方向性を記載）
//   products      : 関連商品カテゴリ（文字列の配列。3〜5件）
//   targets       : 提案先候補（文字列の配列。2〜4件）
//   talkExample   : 営業トーク例（1〜2文。そのまま使えるセリフ形式で）
//   caution       : 注意点（1〜2文。健康効果・機能性の断定は禁止）
//   sources       : 根拠URL（label と url のオブジェクト配列。1〜3件）
//   icon          : トレンドを象徴する絵文字1つ
//
//   ▼ カテゴリ一覧と色コード
//
//   カテゴリ名                    | 色コード
//   ─────────────────────────────────────────
//   'スイーツ・洋菓子'            | '#10B981'  （エメラルドグリーン）
//   'パン・ベーカリー'            | '#F5A623'  （ゴールドアンバー）
//   '冷凍食品・冷凍スイーツ'      | '#60A5FA'  （ライトブルー）
//   'カフェメニュー'              | '#A78BFA'  （ラベンダー）
//   '健康志向・高付加価値食品'    | '#34D399'  （ライトグリーン）
//
//   ▼ sources（根拠URL）の記入例
//
//   sources: [
//     {
//       label: 'メディア名 — 記事タイトル',
//       url: 'https://example.com/article',
//     },
//   ],
//
// =============================================================================
// 【STEP 3 — emailContent（社内配信用メール文案）を書き換える】
// =============================================================================
//
//   emailContent オブジェクト（ファイル末尾付近）の subject と body を
//   今週の内容に書き換えます。
//
//   ▼ subject（件名）の書き換え例
//     '【営業企画部より】今週の食品・外食トレンドTOP3と提案の切り口（5/1号）'
//     ※ 末尾の日付部分を今週の発行日に変更してください。
//
//   ▼ body（本文）の書き換えポイント
//     ・「今週の注目トレンドTOP3」の各項目（■ 1. ■ 2. ■ 3.）を今週のTOP3に変更
//     ・各項目の「提案のヒント（▶）」を今週の営業切り口に変更
//     ・「今週の営業で使える一言」を今週のキーメッセージに変更
//     ・冒頭の季節感のある一文（「初夏〜秋に向けた...」など）を時期に合わせて変更
//
//   ▼ メール文案の作成指針
//     ・A4 1枚以内・3分以内で読める長さを維持する
//     ・健康効果・医療効果・機能性は断定しない
//     ・営業担当がそのままコピーして送れる完成度にする
//
// =============================================================================
// 【STEP 4 — 動作確認チェックリスト】
// =============================================================================
//
//   □ トップページのヒーローセクションに今週の号数が表示されている
//   □ TOP5トレンドカードが5件すべて表示されている
//   □ 各トレンドをクリックすると詳細・営業ツールが展開される
//   □ 評価マトリクス一覧の点数が今週のデータと一致している
//   □ メール文案セクションの件名・本文が今週の内容になっている
//   □ 「絞り込み印刷」ダイアログのカテゴリ件数が正しい
//   □ archiveData.ts の前号が isLatest: false になっている
//
// =============================================================================
// 【よくある間違いと対処法】
// =============================================================================
//
//  ❌ totalScore と scores の合計が一致しない
//     → scores の5項目を足した値が totalScore と同じになるよう確認してください。
//       例: 話題性4 + 検索需要5 + メディア露出5 + 業務用接続性4 + 継続可能性4 = 22
//
//  ❌ sources の url が空・無効
//     → 根拠URLは必ず実在するページのURLを記入してください。
//       確認できない場合は sources を空配列（[]）にして caution に
//       「根拠URL確認中」と記載するのが安全です。
//
//  ❌ emailContent の body 内の改行が崩れる
//     → body はバッククォート（`）で囲まれたテンプレートリテラルです。
//       改行はそのまま反映されます。インデントの空白が本文に入らないよう注意してください。
//
// =============================================================================
// TREND DATA — 2026年5月第1週（← 毎週ここを更新してください）
// Design: Modern Dashboard × Premium Report
// =============================================================================
