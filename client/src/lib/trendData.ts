//   title         : トレンドのフルタイトル（20〜40文字程度）
//   shortTitle    : 評価マトリクス表に表示する短縮タイトル（10〜15文字程度）
//   category      : 下記「カテゴリ一覧」から選択
//   categoryColor : カテゴリに対応する色コード（下記「カテゴリ一覧」参照）
